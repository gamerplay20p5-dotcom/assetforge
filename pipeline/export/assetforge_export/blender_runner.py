"""Executed INSIDE Blender (``blender -b --python blender_runner.py -- config.json``).

It never evaluates user-provided code: the only inputs are a JSON config written by the worker, a
geometry NPZ and PNG textures generated by AssetForge itself. Outputs: model.blend, model.glb,
model.fbx (according to ``formats``) and thumbnail.png.

Coordinate handling: the mesh spec is glTF-style (Y-up, +Z front). Blender is Z-up, so vertices are
stored as (x, -z, y); the glTF exporter (+Y up) converts them back, and FBX is exported with
-Z forward / +Y up for Unity.
"""

from __future__ import annotations

import json
import math
import sys
import traceback
from pathlib import Path

import bpy  # type: ignore[import-not-found]
import numpy as np
from mathutils import Vector  # type: ignore[import-not-found]


def log(msg: str) -> None:
    print(f"[assetforge-blender] {msg}", flush=True)


def event(name: str, status: str) -> None:
    print("@@EVENT " + json.dumps({"stage": name, "status": status}), flush=True)


def load_config() -> dict:
    argv = sys.argv[sys.argv.index("--") + 1:]
    return json.loads(Path(argv[0]).read_text(encoding="utf-8"))


def srgb_to_linear(c: float) -> float:
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def hex_linear(h: str) -> tuple[float, float, float, float]:
    h = h.lstrip("#")
    return (*(srgb_to_linear(int(h[i:i + 2], 16) / 255) for i in (0, 2, 4)), 1.0)


def make_material(name: str, spec: dict, textures: dict) -> "bpy.types.Material":
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    nt = mat.node_tree
    nt.nodes.clear()
    out = nt.nodes.new("ShaderNodeOutputMaterial")
    bsdf = nt.nodes.new("ShaderNodeBsdfPrincipled")
    bsdf.inputs["Roughness"].default_value = spec["roughness"]
    bsdf.inputs["Metallic"].default_value = spec["metallic"]
    color = hex_linear(spec["color"])
    if spec.get("texture") and spec["texture"] in textures:
        img = bpy.data.images.load(textures[spec["texture"]], check_existing=True)
        img.colorspace_settings.name = "sRGB"
        tex = nt.nodes.new("ShaderNodeTexImage")
        tex.image = img
        tex.interpolation = "Linear"
        tex.extension = "REPEAT"
        mix = nt.nodes.new("ShaderNodeMix")
        mix.data_type = "RGBA"
        mix.blend_type = "MULTIPLY"
        mix.inputs["Factor"].default_value = 1.0
        mix.inputs["B"].default_value = color
        nt.links.new(tex.outputs["Color"], mix.inputs["A"])
        nt.links.new(mix.outputs["Result"], bsdf.inputs["Base Color"])
    else:
        bsdf.inputs["Base Color"].default_value = color
    nt.links.new(bsdf.outputs["BSDF"], out.inputs["Surface"])
    return mat


def build_scene(cfg: dict):
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.unit_settings.system = "METRIC"
    scene.unit_settings.scale_length = 1.0
    root = bpy.data.objects.new(cfg["asset_name"], None)
    bpy.context.collection.objects.link(root)
    root.empty_display_type = "PLAIN_AXES"
    data = np.load(cfg["spec_npz"])
    names = sorted({k.rsplit("__", 1)[0] for k in data.files})
    objects = []
    for name in names:
        v = data[f"{name}__v"].astype(np.float64)
        uv = data[f"{name}__uv"].astype(np.float64)
        f = data[f"{name}__f"].astype(np.int64)
        bv = np.stack([v[:, 0], -v[:, 2], v[:, 1]], axis=1)  # glTF Y-up -> Blender Z-up
        mesh = bpy.data.meshes.new(name)
        mesh.from_pydata(bv.tolist(), [], f.tolist())
        uvl = mesh.uv_layers.new(name="UVMap")
        loop_v = np.empty(len(mesh.loops), dtype=np.int32)
        mesh.loops.foreach_get("vertex_index", loop_v)
        uvl.data.foreach_set("uv", uv[loop_v].reshape(-1))
        mesh.polygons.foreach_set("use_smooth", np.zeros(len(mesh.polygons), dtype=bool))
        mesh.update()
        mesh.validate()
        obj = bpy.data.objects.new(name, mesh)
        bpy.context.collection.objects.link(obj)
        obj.parent = root
        obj.data.materials.append(make_material(name, cfg["materials"][name], cfg["textures"]))
        objects.append(obj)
    bpy.context.view_layer.update()
    return root, objects


def bounds(objects) -> tuple[Vector, Vector]:
    pts = [obj.matrix_world @ Vector(c) for obj in objects for c in obj.bound_box]
    lo = Vector((min(p.x for p in pts), min(p.y for p in pts), min(p.z for p in pts)))
    hi = Vector((max(p.x for p in pts), max(p.y for p in pts), max(p.z for p in pts)))
    return lo, hi


def render_thumbnail(cfg: dict, objects) -> None:
    scene = bpy.context.scene
    lo, hi = bounds(objects)
    centre = (lo + hi) / 2
    radius = (hi - lo).length / 2
    # ground disc
    bpy.ops.mesh.primitive_circle_add(vertices=64, radius=radius * 1.35, fill_type="NGON",
                                      location=(centre.x, centre.y, lo.z - 0.01))
    ground = bpy.context.active_object
    gmat = bpy.data.materials.new("ground")
    gmat.use_nodes = True
    gmat.node_tree.nodes["Principled BSDF"].inputs["Base Color"].default_value = (0.30, 0.38, 0.27, 1)
    gmat.node_tree.nodes["Principled BSDF"].inputs["Roughness"].default_value = 1.0
    ground.data.materials.append(gmat)
    # world
    world = bpy.data.worlds.new("w")
    world.use_nodes = True
    bg = world.node_tree.nodes["Background"]
    bg.inputs["Color"].default_value = (0.80, 0.85, 0.92, 1)
    bg.inputs["Strength"].default_value = 0.9
    scene.world = world
    # sun
    sun = bpy.data.lights.new("sun", "SUN")
    sun.energy = 3.2
    sun.angle = math.radians(6)
    sun_obj = bpy.data.objects.new("sun", sun)
    bpy.context.collection.objects.link(sun_obj)
    sun_obj.rotation_euler = (math.radians(52), 0, math.radians(-35))
    # camera
    cam = bpy.data.cameras.new("cam")
    cam.lens = 50
    cam_obj = bpy.data.objects.new("cam", cam)
    bpy.context.collection.objects.link(cam_obj)
    yaw, pitch = math.radians(38), math.radians(24)
    dist = radius * 3.0
    cam_obj.location = centre + Vector((math.sin(yaw) * math.cos(pitch), -math.cos(yaw) * math.cos(pitch),
                                        math.sin(pitch))) * dist
    direction = centre - cam_obj.location
    cam_obj.rotation_euler = direction.to_track_quat("-Z", "Y").to_euler()
    scene.camera = cam_obj
    size = int(cfg.get("thumbnail_size", 512))
    scene.render.resolution_x = scene.render.resolution_y = size
    scene.render.resolution_percentage = 100
    scene.render.engine = "CYCLES"
    scene.cycles.device = "CPU"
    scene.cycles.samples = int(cfg.get("thumbnail_samples", 24))
    scene.cycles.use_denoising = False
    scene.view_settings.view_transform = "Standard"
    scene.render.image_settings.file_format = "PNG"
    scene.render.filepath = str(Path(cfg["out_dir"]) / cfg.get("thumbnail_name", "thumbnail.png"))
    bpy.ops.render.render(write_still=True)
    # remove helper objects so they do not reach exports (exports run before; kept for safety)
    for o in (ground, sun_obj, cam_obj):
        bpy.data.objects.remove(o, do_unlink=True)


def main() -> None:
    cfg = load_config()
    out = Path(cfg["out_dir"])
    out.mkdir(parents=True, exist_ok=True)
    log(f"Blender {bpy.app.version_string}")
    event("build_scene", "start")
    root, objects = build_scene(cfg)
    event("build_scene", "done")
    formats = cfg["formats"]
    event("export_blend", "start")
    bpy.ops.wm.save_as_mainfile(filepath=str(out / "model.blend"), compress=True)
    event("export_blend", "done")
    event("export_glb", "start")
    bpy.ops.export_scene.gltf(filepath=str(out / "model.glb"), export_format="GLB", export_yup=True,
                              export_apply=True, export_texcoords=True, export_normals=True,
                              export_materials="EXPORT", export_cameras=False, export_lights=False,
                              use_selection=False)
    event("export_glb", "done")
    if "fbx" in formats:
        event("export_fbx", "start")
        bpy.ops.export_scene.fbx(filepath=str(out / "model.fbx"), use_selection=False, object_types={"MESH", "EMPTY"},
                                 apply_scale_options="FBX_SCALE_UNITS", axis_forward="-Z", axis_up="Y",
                                 bake_space_transform=True, mesh_smooth_type="FACE", path_mode="COPY",
                                 embed_textures=True, use_mesh_modifiers=True)
        event("export_fbx", "done")
    event("thumbnail", "start")
    render_thumbnail(cfg, objects)
    event("thumbnail", "done")
    log("finished")


if __name__ == "__main__":
    try:
        main()
    except Exception:  # noqa: BLE001
        traceback.print_exc()
        sys.exit(3)
